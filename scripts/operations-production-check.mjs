import fs from "node:fs";
const read=(p)=>fs.readFileSync(p,"utf8");
const must=(ok,msg)=>{if(!ok)throw new Error(msg)};
const runtime=read("packages/runtime/src/index.ts");
const db=read("packages/database/src/prisma.ts");
const dbIndex=read("packages/database/src/index.ts");
const claims=read("apps/worker-claims/src/main.ts");
const fees=read("apps/worker-fees/src/main.ts");
const route=read("apps/bridge/app/api/v1/workers/readiness/route.ts");
must(runtime.includes("Promise.race([input.run(), timeout])"),"worker tick must be hard-bounded");
must(runtime.includes("controller.abort(error)"),"tick timeout must fail closed");
must(runtime.includes("throwIfAborted"),"runtime abort helper missing");
must(claims.includes("throwIfAborted(signal)"),"claim worker ignores shutdown signal");
must(fees.includes("throwIfAborted(signal)"),"fee worker ignores shutdown signal");
for(const key of ["POWERCHAIN_DB_POOL_MAX","POWERCHAIN_DB_CONNECT_TIMEOUT_MS","POWERCHAIN_DB_IDLE_TIMEOUT_MS"]) must(db.includes(key),`db pool config missing ${key}`);
must(dbIndex.includes("getWorkerReadiness"),"worker readiness query missing");
must(route.includes("x-powerchain-workers"),"sanitized worker readiness route missing");
must(!route.includes("workerId"),"public worker readiness must not expose worker IDs");
console.log("operations-production-check: PASS");
