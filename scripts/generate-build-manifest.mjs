const sha256 = (buffer) => createHash("sha256").update(buffer).digest("hex");
const artifacts = files.map((file) => ({ path: file, sha256: sha256(fs.readFileSync(path.join(root, file))) }));
const manifest = {
  schema: "powerchain-build-manifest/v1",
  version: "1.0.0",
  algorithm: "sha256",
  informationCommitment: token.informationCommitment.digest,
  artifacts,
};
const output = `${JSON.stringify(manifest, null, 2)}\n`;
const target = path.join(root, "build-manifest.json");
if (process.argv.includes("--check")) {
  if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== output) {
    console.error("build-manifest.json is stale; run pnpm build-manifest:generate");
    process.exit(1);
  }
  console.log(`Build manifest PASS — ${artifacts.length} artifacts`);
} else {
  fs.writeFileSync(target, output);
  console.log(`Generated build-manifest.json — ${artifacts.length} artifacts`);
}
